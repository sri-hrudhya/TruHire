import http from 'node:http';
import axios from 'axios';
import { cachingAdapter, clearRequestCache } from '../src/lib/requestCache.js';
const hits = {};
const server = http.createServer((req, res) => { const k = req.method + ' ' + req.url.split('?')[0]; hits[k] = (hits[k] || 0) + 1;
  res.setHeader('content-type', 'application/json'); res.end(JSON.stringify({ n: hits[k] })); }).listen(0);
await new Promise(r => server.on('listening', r));
const api = axios.create({ baseURL: `http://127.0.0.1:${server.address().port}/api`, adapter: cachingAdapter });
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) process.exitCode = 1; };
const get = (u, cfg) => api.get(u, cfg).then(r => r.data.n);
await get('/job-descriptions'); await get('/job-descriptions');
ok(hits['GET /api/job-descriptions'] === 1, 'repeat GET served from cache (1 network call)');
await Promise.all([get('/analytics/overview'), get('/analytics/overview'), get('/analytics/overview')]);
ok(hits['GET /api/analytics/overview'] === 1, 'concurrent identical GETs share one request');
await get('/job-descriptions', { headers: { 'X-Cache-Bypass': '1' } });
ok(hits['GET /api/job-descriptions'] === 2, 'X-Cache-Bypass forces a fresh read');
await get('/ingest/history'); await get('/ingest/history');
ok(hits['GET /api/ingest/history'] === 2, 'history is never client-cached');
await api.post('/job-descriptions', {});
await get('/job-descriptions'); await get('/analytics/overview');
ok(hits['GET /api/job-descriptions'] === 3 && hits['GET /api/analytics/overview'] === 2, 'writing a JD evicts JD list + analytics');
await get('/email/config'); await api.post('/search', {}); await get('/email/config');
ok(hits['GET /api/email/config'] === 1, 'unrelated write (search) leaves other cached reads alone');
const a = await api.get('/candidates'); a.data.n = 999; const b = await api.get('/candidates');
ok(b.data.n !== 999, 'cached data is cloned (callers cannot corrupt the cache)');
clearRequestCache(); await get('/email/config');
ok(hits['GET /api/email/config'] === 2, 'clearRequestCache() (logout) empties it');
server.close();
